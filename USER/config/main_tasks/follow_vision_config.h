#ifndef __FOLLOW_VISION_CONFIG_H
#define __FOLLOW_VISION_CONFIG_H

/*
 * 循迹+视觉综合任务参数
 *
 * L/R 入环岛：三层保险（视觉预告 + 编码器空间门控 + 强路口确认 + 找线）
 *
 *   1) K210 识别 L/R：
 *      - 只保存方向；
 *      - 对应转向灯立即闪烁；
 *      - 小车继续正常循迹，不立即转弯。
 *
 *   2) 已有 L/R 待执行时：
 *      - 先用编码器累计距离做"空间门控"，未到距离前绝不启动路口动作；
 *      - 正常单线仍交给 LineFollow；
 *      - 解锁后只接受"方向相关宽路口"，或更靠后的稳定四路全白；
 *      - 短全白先当作地面噪声，不让 LineFollow 立刻按 last_turn 搜线。
 *
 *   3) 路口确认后：
 *      - 先停车 1 秒；
 *      - 完全停止调用 LineFollow；
 *      - 根据 L/R 做对应物理方向原地差速转弯；
 *      - 直到中间传感器重新稳定识别到黑线。
 *
 *   4) 入岛后：
 *      - 岛内循迹一段固定时间；
 *      - 原地旋转出岛（先脱当前线再找新线）；
 *      - 恢复 FOLLOW / SLOW。
 */

/* ---- 循迹参数 ---- */
#define FV_LINE_BASE_SPEED      2850    /* 初始正常循迹直行速度 */
#define FV_LINE_SLOW_SPEED      2100    /* 限速时循迹降速 */
#define FV_LINE_RELEASE_SPEED   2300    /* 解除限速后循迹速度 */

/* ============================================================
 * 入环岛：编码器空间门控
 * ============================================================ */

/*
 * 第一层保险：视觉只是"预告方向"，不是"允许立即转弯"。
 *
 * 收到 L/R 后先累计编码器运动量。只有同时满足：
 *   1) 已经过最短时间；
 *   2) 四轮平均绝对编码器累计量达到 ARM_DISTANCE_COUNTS；
 * 才解锁路口检测。
 *
 * 当前 encoder_config.h 为 780 counts / 轮转一圈，因此 900 counts
 * 约等于 1.15 圈的轮上运动量。实车只需要调这个参数即可。
 */
#define FV_ISLAND_ARM_MIN_MS                     250
#define FV_ISLAND_ARM_DISTANCE_COUNTS          900UL

/*
 * 四路全白最容易由地面反光、拼缝、脏污造成，所以它要比"方向相关
 * 的宽黑路口"再多走一段，才有资格作为路口候选。
 */
#define FV_ISLAND_WHITE_EXTRA_DISTANCE_COUNTS  350UL

/* ============================================================
 * 入环岛：路口图样确认
 * ============================================================ */

/*
 * 第二层保险：路口图样确认。
 *
 * 强路口不再是"任意 >=3 黑"，而是 follow_vision.c 中按 L/R
 * 检查 requested-side 的三探头组合（四路全黑始终算强路口）。
 * 两类候选都必须连续稳定一段时间，过滤 1~10 ms 的路面毛刺。
 */
#define FV_ISLAND_WIDE_CONFIRM_MS                 18
#define FV_ISLAND_WHITE_CONFIRM_MS                35

/*
 * 在路口检测尚未解锁、或全白尚未达到额外距离门槛时：
 * 短全白先保持直行若干 ms，不让 LineFollow 立即进入丢线搜索；
 * 若全白持续更久，才交还普通 LineFollow 做真正的丢线恢复。
 */
#define FV_ISLAND_EARLY_WHITE_HOLD_MS             20

/*
 * 路口候选确认期间只保持较低直行速度，不允许 LineFollow
 * 擅自开始左/右搜索，防止到路口瞬间冲偏。
 */
#define FV_ISLAND_APPROACH_SPEED               2200

/* 视觉提前看到路牌后，最长等待路口时间。超时就取消待转任务。 */
#define FV_ISLAND_WAIT_TIMEOUT_MS            10000

/* ============================================================
 * 入环岛：路口停车
 * ============================================================ */

/* 确认路口后整车停车 1 秒。 */
#define FV_ISLAND_STOP_MS                      1000

/*
 * 前 60ms 使用能耗制动快速刹住，之后使用普通停止，
 * 避免整整 1 秒都让 H 桥处于能耗制动状态。
 */
#define FV_ISLAND_BRAKE_MS                       60

/* ============================================================
 * 入环岛：旋转找线
 * ============================================================ */

/*
 * 转弯阶段不调用 LineFollow，电机完全由 FollowVision 独占。
 * PWM 太高容易扫过黑线，默认 2600 比原 3000 更容易
 * 让四路传感器稳定捕获路线。
 */
#define FV_ISLAND_ROT_SPEED                    2600

/*
 * 开始转弯后至少转这么久，才允许把传感器命中当成"新路线"。
 * 避免停车时原有路口黑线仍在中间探头下，导致刚开始转就误判完成。
 */
#define FV_ISLAND_MIN_MS                        160

/*
 * 判断已经离开旧路口：
 * 黑线探头数量 <=2 持续一小段时间后，才允许进入"重新找线"判定。
 */
#define FV_ISLAND_DEPART_MAX_BLACK                2
#define FV_ISLAND_DEPART_CONFIRM_MS               8

/*
 * 新路线判定：
 * 物理中间区域（X1 / X3）至少一只压黑，且总压黑数 <=2，
 * 连续稳定若干 ms 后认为已经转到新路线。
 */
#define FV_ISLAND_LINE_CONFIRM_MS                12

/* 防止机械故障或传感器异常造成永久原地旋转。 */
#define FV_ISLAND_MAX_MS                       2200

/* ============================================================
 * 岛内循迹 + 出岛
 * ============================================================ */

#define FV_ISLAND_RUN_MS              250     /* 岛内循迹时长 ms */
#define FV_ISLAND_FOLLOW_SPEED        2300    /* 岛内循迹速度 (≥2100) */

/* ---- 鸣笛自动关闭 ---- */
#define FV_HORN_MS              1000    /* 蜂鸣器响持续时间 ms */

/* ---- K210 心跳 ---- */
#define FV_K210_HEARTBEAT_MS    1000    /* STM32 发心跳间隔 ms */

/* ---- OLED 调试 ---- */
#define FV_OLED_ENABLE          0       /* 1=OLED 实时显示, 0=禁用 */
#define FV_DISPLAY_MS           80      /* OLED 刷新间隔 ms */

#endif /* __FOLLOW_VISION_CONFIG_H */
